import assert from 'node:assert/strict';
import { register } from 'node:module';
register('./baser-module-loader.mjs', import.meta.url);
const THREE = await import('three');
const { createWorldBoundsReader } = await import('../baser/src/world-bounds.js');
const readBounds = createWorldBoundsReader();
const geometry = new THREE.BufferGeometry();
const position = new THREE.Float32BufferAttribute([0, 0, 0, 2, 0, 0, 0, 1, 0], 3);
geometry.setAttribute('position', position);
const mesh = new THREE.Mesh(geometry);
const check = (bounds, minimum, maximum) => {
    minimum.forEach((value, i) => assert.ok(Math.abs(bounds.min.getComponent(i) - value) < 1e-6));
    maximum.forEach((value, i) => assert.ok(Math.abs(bounds.max.getComponent(i) - value) < 1e-6));
};
check(readBounds(mesh), [0, 0, 0], [2, 1, 0]);
let vertexReads = 0;
const getX = position.getX;
position.getX = function(index) { vertexReads++; return getX.call(this, index); };
const disposableCopy = readBounds(mesh);
disposableCopy.makeEmpty();
check(readBounds(mesh), [0, 0, 0], [2, 1, 0]);
assert.equal(vertexReads, 0, 'unchanged large scans must not be re-read for text edits');
mesh.rotation.z = Math.PI / 4;
check(readBounds(mesh), [-Math.SQRT1_2, 0, 0], [Math.SQRT2, Math.SQRT2, 0]);
assert.ok(vertexReads > 0, 'rotation must invalidate cached bounds');
mesh.position.set(10, 20, 30);
check(readBounds(mesh), [10 - Math.SQRT1_2, 20, 30], [10 + Math.SQRT2, 20 + Math.SQRT2, 30]);
position.setXYZ(1, 4, 0, 0);
position.needsUpdate = true;
check(readBounds(mesh), [10 - Math.SQRT1_2, 20, 30], [10 + 2 * Math.SQRT2, 20 + 2 * Math.SQRT2, 30]);
geometry.setAttribute('position', new THREE.Float32BufferAttribute([0, 0, 0, 1, 0, 0, 0, 1, 0], 3));
check(readBounds(mesh), [10 - Math.SQRT1_2, 20, 30], [10 + Math.SQRT1_2, 20 + Math.SQRT1_2, 30]);
const replacement = new THREE.BoxGeometry(2, 2, 2);
mesh.geometry = replacement;
mesh.rotation.set(0, 0, 0);
check(readBounds(mesh), [9, 19, 29], [11, 21, 31]);
const child = new THREE.Mesh(new THREE.BoxGeometry(100, 100, 100));
mesh.add(child);
check(readBounds(mesh), [9, 19, 29], [11, 21, 31]);
geometry.dispose(); replacement.dispose(); child.geometry.dispose();
console.log('PASS exact model bounds: cached reads, isolated results, rotation, translation, vertex edits, geometry replacement, and child exclusion.');
